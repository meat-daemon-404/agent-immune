import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test } from 'node:test';
import { ciCheck, parseManagedBlock, shareSanityCheck } from '../dsh-immune-system/dist/core/share-guard.js';
import { SECTION_START, SECTION_END } from '../dsh-immune-system/dist/core/sync-doc.js';

test('3.2 share gate: machine paths and secret-shaped text block an export', () => {
  const clean = { trigger_pattern: 'Bash npm test', symptom: 'tests not run', prescription: 'run npm test first' };
  const withPath = {
    trigger_pattern: 'Edit D:\\repos\\shop\\src\\a.ts',
    symptom: 'file edited blind',
    prescription: 'read first',
  };
  const withSecret = {
    trigger_pattern: 'curl api',
    symptom: 'password=hunter2supersecret text',
    prescription: 'use the env var',
  };

  assert.deepEqual(shareSanityCheck([clean]), [], 'clean rules pass');
  const pathViolations = shareSanityCheck([withPath]);
  assert.equal(pathViolations.length, 1);
  assert.equal(pathViolations[0].kind, 'machine-path');
  assert.equal(pathViolations[0].field, 'trigger_pattern');
  const secretViolations = shareSanityCheck([withSecret]);
  assert.equal(secretViolations.length, 1);
  assert.equal(secretViolations[0].kind, 'secret-shaped');
});

test('3.2 managed-block parser reads the three-line rule format sync-doc writes', () => {
  const dir = mkdtempSync(join(tmpdir(), 'immune-share-'));
  try {
    const doc = join(dir, 'AGENTS.md');
    writeFileSync(
      doc,
      [
        '# header',
        SECTION_START,
        '',
        '## Pitfall antibodies (auto-generated by dsh-immune)',
        '',
        '- **auto sync probe**',
        '  - 忌/avoid: s',
        '  - 宜/do: p',
        '',
        '<sub>Rules learned …</sub>',
        SECTION_END,
        '',
      ].join('\n'),
      'utf8',
    );
    const rules = parseManagedBlock(doc);
    assert.equal(rules.length, 1);
    assert.equal(rules[0].trigger_pattern, 'auto sync probe');
    assert.equal(rules[0].prescription, 'p');
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('3.2 ci-check: a diff line touching a managed trigger is a finding', () => {
  const rules = [{ trigger_pattern: 'npm run build vite', symptom: '', prescription: '' }];
  const diff = [
    'diff --git a/x.js b/x.js',
    '--- a/x.js',
    '+++ b/x.js',
    '@@ -1,2 +1,3 @@',
    ' unchanged line',
    '-removed line',
    '+const cmd = "npm run build"',
    '+totally unrelated addition',
  ].join('\n');
  const report = ciCheck(diff, rules);
  assert.equal(report.addedLines, 2);
  assert.equal(report.findings.length, 1, 'only the line naming the trigger territory fires');
  assert.ok(report.findings[0].text.includes('npm run build'));
  assert.equal(ciCheck(diff, []).findings.length, 0, 'no rules, no findings');
});

test('3.2 share gate + echo detector do not mistake https:// URLs for Windows paths', async () => {
  const { looksEchoPrescription } = await import('../dsh-immune-system/dist/core/rewrite.js');
  const withUrl = {
    trigger_pattern: 'Bash curl bilibili',
    symptom: 'HTTP 412 precondition failed on https://www.bilibili.com/video/BV1',
    prescription: 'Edit: pass explicit headers before requesting https://www.bilibili.com/api',
  };
  assert.deepEqual(
    shareSanityCheck([withUrl]),
    [],
    'https:// must not trigger Windows drive-letter detection (s://)',
  );
  assert.equal(looksEchoPrescription(withUrl.prescription), false, 'URL after Edit: is not a local file path');
  assert.equal(looksEchoPrescription('Edit: C:\\repo\\secret.ts'), true, 'real Windows drive path is still flagged');
  assert.equal(looksEchoPrescription('bash: npm run build -- --mode production'), true, 'lowercase bash: is caught');
});
