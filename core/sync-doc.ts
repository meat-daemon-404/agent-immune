/**
 * Write the library's proven rules into the project's agent docs
 * (AGENTS.md / CLAUDE.md) as a managed section.
 *
 * Why: not every agent runs our hooks. Every agent worth the name reads
 * AGENTS.md or CLAUDE.md, so a deterministic, idempotent section there
 * extends the immunity to hosts we have not ported to — the same lessons,
 * delivered as plain markdown.
 *
 * The section is fenced by generated markers and fully replaced on every run,
 * so repeated syncs never duplicate. Field text is angle-bracket-stripped
 * before writing (AGENTS.md #18: the writer owns whatever delimiter the
 * downstream consumer parses).
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { Antibody } from './types.js';
import type { ImmuneStore } from './store/index.js';

export const SECTION_START = '<!-- immune:generated start -->';
export const SECTION_END = '<!-- immune:generated end -->';

function stripAngle(value: string): string {
  return value.replace(/[<>]/g, ' ').replace(/\s+/g, ' ').trim();
}

export interface SyncDocOptions {
  /** Target file; created when missing. */
  file: string;
  /** Minimum hit count for a rule to be written (default 3). */
  minHits?: number;
  /** Heading level inside the section. */
  heading?: string;
}

export interface SyncDocReport {
  file: string;
  rules: number;
  created: boolean;
  replaced: boolean;
}

/** Build the managed section body from the store's proven rules. */
export function buildDocSection(store: ImmuneStore, minHits: number, heading: string): string {
  const rows: Antibody[] = store.exportable(minHits);
  const lines: string[] = [SECTION_START, '', heading, ''];
  if (rows.length === 0) {
    lines.push('_No proven antibodies yet — they appear after a tool fails and then succeeds._', '');
  }
  for (const a of rows) {
    lines.push(`- **${stripAngle(a.trigger_pattern)}**`);
    lines.push(`  - 忌/avoid: ${stripAngle(a.symptom)}`);
    lines.push(`  - 宜/do: ${stripAngle(a.prescription)}`);
    const rp = Array.isArray(a.repair_path) ? a.repair_path : [];
    if (rp.length > 0) lines.push(`  - repaired by: ${rp.map(stripAngle).join(' · ')}`);
  }
  // Provenance travels with the section: when a project ships its AGENTS.md
  // to a public repo, the line reads as attribution instead of mystery text.
  lines.push(
    '',
    '<sub>Rules learned from failed-then-fixed tool episodes by [dsh-immune-system](https://github.com/meat-daemon-404/agent-immune).</sub>',
    SECTION_END,
    '');
  return lines.join('\n');
}

/** Create or replace the managed section in the target doc. */
export function syncDoc(store: ImmuneStore, opts: SyncDocOptions): SyncDocReport {
  const file = opts.file;
  const minHits = opts.minHits ?? 3;
  const heading = opts.heading ?? '## Pitfall antibodies (auto-generated by dsh-immune)';
  const section = buildDocSection(store, minHits, heading);

  const existed = existsSync(file);
  const current = existed ? readFileSync(file, 'utf8') : '';
  const startIndex = current.indexOf(SECTION_START);
  const endIndex = current.indexOf(SECTION_END);

  let next: string;
  let replaced = false;
  if (startIndex >= 0 && endIndex > startIndex) {
    next =
      current.slice(0, startIndex) +
      section.trimEnd() +
      '\n' +
      current.slice(endIndex + SECTION_END.length).replace(/^\n+/, '\n');
    replaced = true;
  } else {
    next = current.length > 0 ? current.trimEnd() + '\n\n' + section : section;
  }

  writeFileSync(file, next, 'utf8');
  const rules = (store.exportable(minHits) ?? []).length;
  return { file, rules, created: !existed, replaced };
}

/**
 * Opt-in turn-end auto sync: when `IMMUNE_SYNC_DOC` names a file (or is a
 * truthy non-path like "1", meaning AGENTS.md next to the project root), the
 * drain calls this after distilling, so freshly learned rules reach the docs
 * the same turn. Never throws — a read-only project or a bad path must not
 * cost the user their turn.
 */
export function maybeSyncDocAfterDrain(
  store: ImmuneStore,
  env: NodeJS.ProcessEnv = process.env,
): SyncDocReport | null {
  const raw = env.IMMUNE_SYNC_DOC?.trim();
  if (!raw) return null;
  const defaultFile = env.ZCODE_PROJECT_DIR ? join(env.ZCODE_PROJECT_DIR, 'AGENTS.md') : 'AGENTS.md';
  const file = raw === '1' || raw.toLowerCase() === 'true' ? defaultFile : raw;
  const minHitsRaw = Number(env.IMMUNE_SYNC_DOC_MIN_HITS ?? '');
  try {
    return syncDoc(store, {
      file,
      minHits: Number.isFinite(minHitsRaw) && minHitsRaw >= 0 ? minHitsRaw : 3,
    });
  } catch {
    return null;
  }
}
